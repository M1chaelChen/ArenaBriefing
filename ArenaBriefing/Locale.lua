-- Keep canonical spec names, rule IDs and slash commands locale-independent.
function AB.L(key, ...)
    local value = AB.locale == "zhCN" and zhCN[key] or key
    if select("#", ...) > 0 then return string.format(value, ...) end
    return value
end
